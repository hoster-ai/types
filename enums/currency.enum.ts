/**
 * Display metadata for a single currency code.
 *
 * @description - The `code` mirrors the key of {@link CURRENCY_CATALOG}, so a single entry
 *                stays self-describing once it is detached from the map (e.g. serialized
 *                to a client as a list).
 */
export interface CurrencyMetadata {
  /** English currency name (ISO 4217 / CLDR wording). */
  name: string;
  /** Commonly used currency symbol. Falls back to the three-letter code when no distinct symbol exists. */
  symbol: string;
  /** ISO 4217 currency code. */
  code: CurrencyEnum;
}

